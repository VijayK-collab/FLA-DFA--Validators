"""Write docs/diagrams.md with Mermaid state diagrams (GitHub draws them automatically).

    python3 tools/export_mermaid.py
"""

import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from fa_validators.validators import build_email_dfa, build_pin_dfa, has_class


def mermaid(dfa, prefix=""):
    name = lambda q: f"{prefix}{q}"
    lines = ["```mermaid", "stateDiagram-v2", f"    [*] --> {name(dfa.start)}"]
    labels = defaultdict(list)
    for (q, sym), nq in sorted(dfa.delta.items(), key=lambda kv: (str(kv[0][0]), str(kv[0][1]))):
        labels[(q, nq)].append(sym)
    for (q, nq), syms in labels.items():
        lines.append(f"    {name(q)} --> {name(nq)}: {', '.join(syms)}")
    for q in sorted(dfa.accepts, key=str):
        lines.append(f"    {name(q)} --> [*]")
    lines.append("```")
    return "\n".join(lines)


def main():
    parts = ["# State diagrams", "",
             "Generated by `tools/export_mermaid.py`. A missing arrow means a move to the dead state (reject).", "",
             "## ATM PIN (4 or 6 digits, D = digit)", "", mermaid(build_pin_dfa()), "",
             "## E-mail format (A = letter or digit)", "", mermaid(build_email_dfa()), "",
             "## Password: one component DFA, 'contains an upper-case letter'", "",
             mermaid(has_class("U"), prefix="s"), "",
             "The full password machine is the product of five such components "
             "(see `intersect` in `fa_validators/automata.py`); it is too large to draw by hand.", ""]
    out = os.path.join(os.path.dirname(__file__), "..", "docs", "diagrams.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print("wrote", os.path.normpath(out))


if __name__ == "__main__":
    main()
